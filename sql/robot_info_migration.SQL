-- CampusMate: data the robot needs (rooms directions, bilingual courses, staff titles)
-- Run AFTER project.sql and rooms_competitions_migration.sql. Run ONCE.


-- 1) Rooms: directions from the robot + step-free (no stairs) route
ALTER TABLE rooms
    ADD COLUMN directions_from_robot TEXT,
    ADD COLUMN has_step_free_route BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN step_free_directions TEXT;


-- 2) Courses: Arabic name + academic year
--    (course_name stays as the English name so existing code keeps working)
ALTER TABLE Courses
    ADD COLUMN course_name_ar VARCHAR(150),
    ADD COLUMN academic_year SMALLINT
        CHECK (academic_year BETWEEN 1 AND 5);


-- 3) Course nicknames (one course can have several)
CREATE TABLE course_aliases (
    alias_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    alias VARCHAR(100) NOT NULL,

    FOREIGN KEY (course_id)
        REFERENCES Courses(course_id)
        ON DELETE CASCADE,

    UNIQUE (course_id, alias)
);

CREATE INDEX idx_course_aliases_alias ON course_aliases (LOWER(alias));


-- 4) Staff: title (e.g. Prof. Dr., Dr., Eng.)
ALTER TABLE staff
    ADD COLUMN title VARCHAR(30);


-- 5) Flat "directory" views, one row per room / course / staff member
CREATE VIEW rooms_directory AS
SELECT
    r.room_id,
    r.room_code,
    b.building_name,
    f.floor_number,
    r.room_type,
    r.capacity,
    r.directions_from_robot,
    r.has_step_free_route,
    r.step_free_directions
FROM rooms r
JOIN floors f ON f.floor_id = r.floor_id
JOIN buildings b ON b.building_id = f.building_id
WHERE r.status = 'Active';


CREATE VIEW courses_directory AS
SELECT
    c.course_id,
    c.course_code,
    c.course_name AS name_en,
    c.course_name_ar AS name_ar,
    c.academic_year,
    d.department_name,
    COALESCE(string_agg(a.alias, ', ' ORDER BY a.alias), '') AS aliases
FROM Courses c
LEFT JOIN Departments d ON d.department_id = c.department_id
LEFT JOIN course_aliases a ON a.course_id = c.course_id
WHERE c.status = 'Active'
GROUP BY c.course_id, d.department_name;


CREATE VIEW staff_directory AS
SELECT
    s.staff_id,
    s.staff_code,
    s.title,
    s.first_name,
    s.last_name,
    s.role,
    d.department_name,
    s.email,
    r.room_code AS office_room,
    b.building_name AS office_building,
    f.floor_number AS office_floor
FROM staff s
LEFT JOIN Departments d ON d.department_id = s.department_id
LEFT JOIN rooms r ON r.room_id = s.office_room_id
LEFT JOIN floors f ON f.floor_id = r.floor_id
LEFT JOIN buildings b ON b.building_id = f.building_id
WHERE s.status = 'Active';