-- 2) Doctor / staff status: ONE row per staff member (their current status)
CREATE TABLE staff_status (
    staff_id INT PRIMARY KEY,

    status VARCHAR(20) NOT NULL DEFAULT 'Unknown'
        CHECK (status IN ('Available', 'In Lecture', 'Office Hours',
                          'Busy', 'Away', 'On Leave', 'Unknown')),

    room_id INT,
    note TEXT,
    status_until TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (staff_id)
        REFERENCES staff(staff_id)
        ON DELETE CASCADE,

    FOREIGN KEY (room_id)
        REFERENCES rooms(room_id)
        ON DELETE SET NULL
);

CREATE TRIGGER trg_staff_status_updated_at
BEFORE UPDATE ON staff_status
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- A status with an end time that has passed is shown as 'Unknown'
CREATE VIEW staff_status_view AS
SELECT
    s.staff_id,
    s.title,
    s.first_name,
    s.last_name,
    s.role,
    CASE
        WHEN ss.status_until IS NOT NULL AND ss.status_until < CURRENT_TIMESTAMP
            THEN 'Unknown'
        ELSE COALESCE(ss.status, 'Unknown')
    END AS current_status,
    r.room_code AS location_room,
    b.building_name AS location_building,
    f.floor_number AS location_floor,
    ss.note,
    ss.status_until,
    ss.updated_at AS last_updated
FROM staff s
LEFT JOIN staff_status ss ON ss.staff_id = s.staff_id
LEFT JOIN rooms r ON r.room_id = ss.room_id
LEFT JOIN floors f ON f.floor_id = r.floor_id
LEFT JOIN buildings b ON b.building_id = f.building_id
WHERE s.status = 'Active';


-- 3) Schedule (the lectures table): add 'Lab', check times, tie semester to terms
ALTER TABLE Schedule DROP CONSTRAINT IF EXISTS schedule_session_type_check;
ALTER TABLE Schedule
    ADD CONSTRAINT schedule_session_type_check
    CHECK (session_type IN ('Lecture', 'Section', 'Lab'));

ALTER TABLE Schedule
    ADD CONSTRAINT schedule_time_order_check
    CHECK (end_time > start_time);

ALTER TABLE Schedule
    ADD CONSTRAINT fk_schedule_term
    FOREIGN KEY (semester) REFERENCES terms(term_name);


-- 4) Enrollments: one row per student, per course, per term, with the student's group
ALTER TABLE Enrollments DROP COLUMN schedule_id;

ALTER TABLE Enrollments
    ADD COLUMN course_id INT NOT NULL,
    ADD COLUMN group_id INT NOT NULL,
    ADD COLUMN semester VARCHAR(20) NOT NULL;

ALTER TABLE Enrollments
    ADD CONSTRAINT fk_enrollment_course
        FOREIGN KEY (course_id) REFERENCES Courses(course_id),
    ADD CONSTRAINT fk_enrollment_group
        FOREIGN KEY (group_id) REFERENCES student_Groups(group_id),
    ADD CONSTRAINT fk_enrollment_term
        FOREIGN KEY (semester) REFERENCES terms(term_name),
    ADD CONSTRAINT uq_enrollment_student_course_term
        UNIQUE (student_id, course_id, semester);

CREATE INDEX idx_enrollment_course_group_term
    ON Enrollments (course_id, group_id, semester);


-- 5) The enrollments table replaces the "student is in many groups" table:
--    the group now belongs to a (student, course) pair.
DROP VIEW IF EXISTS advisor_students;
DROP TABLE IF EXISTS student_group_members;
ALTER TABLE Students DROP COLUMN IF EXISTS group_id;

CREATE VIEW advisor_students AS
SELECT
    a.advisor_id,
    a.staff_id AS advisor_staff_id,
    s.student_id,
    s.student_code,
    s.first_name,
    s.last_name,
    s.email,
    s.status
FROM advisors a
JOIN Students s
    ON s.advisor_id = a.advisor_id;


-- 6) A student's timetable = their enrollments joined to the matching schedule rows
CREATE VIEW student_timetable AS
SELECT
    e.student_id,
    e.semester,
    sc.schedule_id,
    c.course_code,
    c.course_name,
    c.course_name_ar,
    sc.session_type,
    g.group_name,
    sc.day_of_week,
    sc.start_time,
    sc.end_time,
    COALESCE(r.room_code, sc.room) AS room,
    st.title AS staff_title,
    st.first_name AS staff_first_name,
    st.last_name AS staff_last_name
FROM Enrollments e
JOIN Schedule sc
    ON sc.course_id = e.course_id
   AND sc.group_id = e.group_id
   AND sc.semester = e.semester
JOIN Courses c ON c.course_id = e.course_id
JOIN student_Groups g ON g.group_id = e.group_id
LEFT JOIN rooms r ON r.room_id = sc.room_id
LEFT JOIN staff st ON st.staff_id = sc.staff_id
WHERE e.status = 'Active';