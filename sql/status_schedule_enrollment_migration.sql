-- 1) Terms: one list of valid terms, used by both Schedule and Enrollments
--    so "Fall 2026" can never be typed two different ways.
CREATE TABLE terms (
    term_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_name VARCHAR(20) NOT NULL UNIQUE,
    start_date DATE,
    end_date DATE,
    is_current BOOLEAN NOT NULL DEFAULT FALSE
);

-- only one term can be the current one
CREATE UNIQUE INDEX one_current_term ON terms (is_current) WHERE is_current;

